//! Global keyboard actions and their key bindings.
//!
//! The iced era received raw key events through `event::listen_with`
//! subscriptions; GPUI routes keys through bound [`gpui_kit::Action`]s that
//! dispatch from the focused node and bubble to the shell root, where
//! `on_action` listeners translate them into root `Message`s. Handlers enforce
//! the same mode/state conditions the old subscription filters did (see
//! `ui/shell::handle_action`).
//!
//! Character keys (`?`, digits, `b`/`v`/`c`) and undo/redo are suppressed while
//! a text input owns the window focus, so typing in the global search or any
//! other field never triggers presenter navigation.

