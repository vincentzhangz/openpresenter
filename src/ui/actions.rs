/// Register every app key binding. Called once from the GPUI launch closure.
pub fn bind_keys(cx: &mut App) {
    let mut bindings = vec![
        // Transport. The arrow keys move the selected object while the slide
        // is being edited, and drive the show while it is running, so they
        // are bound once and the handler decides.
        KeyBinding::new("space", NextSlide, None),
        KeyBinding::new("pagedown", NextSlide, None),
        KeyBinding::new("right", NudgeRight, None),
        KeyBinding::new("down", NudgeDown, None),
        KeyBinding::new("left", NudgeLeft, None),
        KeyBinding::new("pageup", PrevSlide, None),
        KeyBinding::new("up", NudgeUp, None),
        KeyBinding::new("home", FirstSlide, None),
        KeyBinding::new("end", LastSlide, None),
        // Nudging an object: one slide pixel, or ten with the shift key.
        KeyBinding::new("shift-right", NudgeRightFast, None),
        KeyBinding::new("shift-down", NudgeDownFast, None),
        KeyBinding::new("shift-left", NudgeLeftFast, None),
        KeyBinding::new("shift-up", NudgeUpFast, None),
        // Group jumps.
        KeyBinding::new("v", JumpToVerse, None),
        KeyBinding::new("c", JumpToChorus, None),
        KeyBinding::new("b", ToggleBlackScreen, None),
        // Layer clears: F1–F6 and Cmd+1–6.
        KeyBinding::new("f1", ClearAll, None),
        KeyBinding::new("f2", ClearSlide, None),
        KeyBinding::new("f3", ClearMedia, None),
        KeyBinding::new("f4", ClearProps, None),
        KeyBinding::new("f5", ClearAudio, None),
        KeyBinding::new("f6", ClearMessages, None),
        // Numeric slide jumps.
        KeyBinding::new("1", GotoSlide1, None),
        KeyBinding::new("2", GotoSlide2, None),
        KeyBinding::new("3", GotoSlide3, None),
        KeyBinding::new("4", GotoSlide4, None),
        KeyBinding::new("5", GotoSlide5, None),
        KeyBinding::new("6", GotoSlide6, None),
        KeyBinding::new("7", GotoSlide7, None),
        KeyBinding::new("8", GotoSlide8, None),
        KeyBinding::new("9", GotoSlide9, None),
        // Global keys.
        KeyBinding::new("?", ToggleShortcuts, None),
        KeyBinding::new("delete", DeleteObject, None),
        KeyBinding::new("backspace", DeleteObject, None),
        KeyBinding::new("shift-cmd-z", Redo, None),
        KeyBinding::new("escape", Escape, None),
    ];
    bindings.extend([
        key_binding("secondary-1", ClearAll, cx),
        key_binding("secondary-2", ClearSlide, cx),
        key_binding("secondary-3", ClearMedia, cx),
        key_binding("secondary-4", ClearProps, cx),
        key_binding("secondary-5", ClearAudio, cx),
        key_binding("secondary-6", ClearMessages, cx),
        key_binding("secondary-,", OpenSettings, cx),
        key_binding("secondary-q", QuitApp, cx),
        key_binding("secondary-h", HideApp, cx),
        key_binding("secondary-alt-h", HideOtherApps, cx),
        key_binding("secondary-z", Undo, cx),
        key_binding("secondary-c", CopyObject, cx),
        key_binding("secondary-v", PasteObject, cx),
        key_binding("secondary-d", DuplicateObject, cx),
        key_binding("secondary-y", Redo, cx),
    ]);
    cx.bind_keys(bindings);
}

/// Build one key binding with the platform's primary modifier.
///
/// `KeyBinding::new` parses a static keystroke on its own, so the universal
/// `secondary-` alias must be resolved against the running OS instead.
fn key_binding<A: gpui_kit::Action>(keystrokes: &str, action: A, cx: &mut App) -> KeyBinding {
    KeyBinding::load(keystrokes, Box::new(action), None, false, None, cx).expect("valid keystroke")
}

